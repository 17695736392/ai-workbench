# ===== 你的资料库（比如店铺售后政策手册）=====
资料 = """夏天榴莲店售后政策：
1. 坏果包赔：收货后24小时内拍照联系客服，坏多少赔多少
2. 开果不满意：包退，运费我们承担
3. 金枕榴莲75元/斤，猫山王150元/斤
4. 发货：下单后48小时内发出，全国包邮
5. 榴莲纯肉分装规格：1斤装/1.5斤装/2斤装/2.5斤装/3斤装
6. 客服工作时间：早9点到晚10点"""

# ===== RAG 三步 =====
# 第1步：拆（把资料切成一句一条，方便查找）
知识库 = [s.strip() for s in 资料.split("\n") if s.strip() and not s.startswith("夏天榴莲店")]

# 第2步：搜（用户提问 → 找出包含相关关键词的资料条目）
def 搜索(问题):
    关键词 = ["坏果", "赔", "包赔", "退款", "发货", "包邮", "价格", "金枕",
             "猫山王", "规格", "上班", "几点", "时间", "不满意", "客服", "工作"]
    命中 = [条 for 条 in 知识库 if any(词 in 条 for 词 in 关键词 if 词 in 问题)]
    return 命中 if 命中 else 知识库[:2]   # 没搜到就兜底给前两条

# 第3步：答（把"搜到的资料 + 用户问题"一起给AI，AI看着资料回答）
def 问答(问题):
    资料片段 = "\n".join(搜索(问题))
    r = client.chat.completions.create(
        model="deepseek-chat",
        messages=[
            {"role": "system", "content": "你是客服助手。只能根据下面【资料】回答，资料里没有的就说'这个我得问老板'：\n【资料】\n" + 资料片段},
            {"role": "user", "content": 问题}
        ]
    )
    return r.choices[0].message.content

